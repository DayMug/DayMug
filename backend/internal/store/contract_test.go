// Package store_test hosts the cross-layer API contract snapshot.
//
// The frontend's request/response types are hand-written and there is no
// codegen keeping them honest, so changing a Go struct's json tags used to be
// a silent break: the backend ships a renamed field, the SPA keeps reading the
// old one, and nothing fails until someone clicks the right button. Codegen
// was evaluated and rejected — most handlers return anonymous gin.H maps, so
// there is very little to generate from, and generated types would flatten the
// literal unions and derived types the frontend deliberately hand-writes.
//
// This snapshot buys the main benefit instead: it pins the JSON field names
// and optionality of the types the SPA actually models. Adding, removing, or
// renaming a field fails this test, which forces the change to be paired with
// a frontend update (or a deliberate exemption). frontend/scripts/
// check-api-contract.mjs reads the same golden file from the other side.
//
// It lives in package store_test (external) so it can import internal/service
// without an import cycle.
package store_test

import (
	"bytes"
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"testing"
	"time"

	"github.com/DayMug/DayMug/backend/internal/service"
	"github.com/DayMug/DayMug/backend/internal/store"
)

var updateContract = flag.Bool("update-contract", false, "rewrite contract.golden.json from the current Go types")

const contractGoldenPath = "contract.golden.json"

// contractType records one Go type in the snapshot plus where the frontend
// models it. The TS coordinates are not used by this test — they tell
// check-api-contract.mjs which interface to compare against, and they tell a
// human reading a failure which file to go fix.
type contractType struct {
	// Sample is a value of the Go type. It is passed through encoding/json
	// rather than reflected over, so types with a custom MarshalJSON are
	// captured as they actually appear on the wire.
	Sample any

	TSInterface string
	TSFile      string
}

// contractTypes is the whitelist. It is deliberately small: these are the
// stable, long-lived payloads the SPA models as named interfaces. Growing it
// is welcome; every entry needs a matching TS interface.
